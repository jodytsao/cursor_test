function 生成訂單資料() {
  const 訂單類型列表 = ['桌邊點餐', '線上點餐', '外帶'];
  const 訂單類型權重 = [0.5, 0.3, 0.2]; // 權重：桌邊50%，線上30%，外帶20%

  let 訂單編號 = 1;
  const 今天 = new Date();

  // 生成過去90天的資料
  for (let 天數偏移 = 90; 天數偏移 >= 0; 天數偏移--) {
    const 日期 = new Date(今天);
    日期.setDate(日期.getDate() - 天數偏移);

    // 根據星期幾調整訂單數量
    const 星期幾 = 日期.getDay();
    const 是否週末 = 星期幾 === 0 || 星期幾 === 6;
    const 基礎訂單數 = 是否週末 ? 50 : 30;
    const 訂單數量 = 基礎訂單數 + Math.floor(Math.random() * 20);

    for (let i = 0; i < 訂單數量; i++) {
      // 生成訂單時間（營業時間 10:00-22:00）
      // 根據時段調整訂單機率（午餐11-14、晚餐17-21 較多）
      let 小時;
      const 時段隨機 = Math.random();
      if (時段隨機 < 0.4) {
        // 40% 午餐時段
        小時 = 11 + Math.floor(Math.random() * 3);
      } else if (時段隨機 < 0.85) {
        // 45% 晚餐時段
        小時 = 17 + Math.floor(Math.random() * 4);
      } else {
        // 15% 其他時段
        小時 = 10 + Math.floor(Math.random() * 12);
      }

      const 分鐘 = Math.floor(Math.random() * 60);
      const 訂單時間 = new Date(日期);
      訂單時間.setHours(小時, 分鐘, 0, 0);

      // 根據權重選擇訂單類型
      const 隨機值 = Math.random();
      let 訂單類型;
      if (隨機值 < 訂單類型權重[0]) {
        訂單類型 = '桌邊點餐';
      } else if (隨機值 < 訂單類型權重[0] + 訂單類型權重[1]) {
        訂單類型 = '線上點餐';
      } else {
        訂單類型 = '外帶';
      }

      // 隨機選擇會員（70%的機率有會員）
      const 會員編號 = Math.random() < 0.7 ? Math.floor(Math.random() * 15) + 1 : null;

      // 只有桌邊點餐才需要桌位
      const 桌位編號 = 訂單類型 === '桌邊點餐' ? Math.floor(Math.random() * 25) + 1 : null;

      // 生成訂單號碼
      const 訂單號碼 = `ORD${日期.getFullYear()}${String(日期.getMonth() + 1).padStart(2, '0')}${String(日期.getDate()).padStart(2, '0')}-${String(訂單編號).padStart(4, '0')}`;

      // 隨機選擇2-6個菜品
      const 品項數量 = 2 + Math.floor(Math.random() * 5);
      const 已選項目 = new Set();
      const 訂單項目 = [];

      while (訂單項目.length < 品項數量) {
        const 菜單項目編號 = Math.floor(Math.random() * 35) + 1;
        if (!已選項目.has(菜單項目編號)) {
          已選項目.add(菜單項目編號);
          const 數量 = 1 + Math.floor(Math.random() * 3);
          訂單項目.push({ 項目編號: 菜單項目編號, 數量 });
        }
      }

      // 查詢實際菜單價格並計算總金額
      let 總金額 = 0;
      let 已處理項目數 = 0;

      訂單項目.forEach(項目 => {
        資料庫.get('SELECT 售價 FROM 菜單項目 WHERE 項目編號 = ?', [項目.項目編號], (錯誤, 資料) => {
          if (!錯誤 && 資料) {
            項目.單價 = 資料.售價;
            項目.小計 = 資料.售價 * 項目.數量;
            總金額 += 項目.小計;
          }

          已處理項目數++;

          // 當所有項目都處理完畢後，插入訂單
          if (已處理項目數 === 訂單項目.length) {
            // 完成時間（用餐時長30-120分鐘）
            const 完成時間 = new Date(訂單時間);
            const 用餐時長 = 訂單類型 === '桌邊點餐' ? 45 + Math.floor(Math.random() * 75) : 15 + Math.floor(Math.random() * 30);
            完成時間.setMinutes(完成時間.getMinutes() + 用餐時長);

            // 插入訂單
            資料庫.run(
              `INSERT INTO 訂單 (訂單號碼, 會員編號, 桌位編號, 訂單類型, 總金額, 訂單狀態, 建立時間, 完成時間)
               VALUES (?, ?, ?, ?, ?, '已完成', ?, ?)`,
              [訂單號碼, 會員編號, 桌位編號, 訂單類型, 總金額, 訂單時間.toISOString(), 完成時間.toISOString()],
              function(錯誤) {
                if (錯誤) {
                  console.error('訂單插入錯誤:', 錯誤);
                  return;
                }

                const 當前訂單編號 = this.lastID;

                // 插入訂單明細
                訂單項目.forEach(項目 => {
                  資料庫.run(
                    `INSERT INTO 訂單明細 (訂單編號, 項目編號, 數量, 單價, 小計)
                     VALUES (?, ?, ?, ?, ?)`,
                    [當前訂單編號, 項目.項目編號, 項目.數量, 項目.單價, 項目.小計]
                  );
                });
              }
            );
          }
        });
      });

      訂單編號++;
    }
  }

  // 等待所有插入完成
  setTimeout(() => {
    console.log(`✓ 已生成約 ${訂單編號 - 1} 筆訂單`);

    // 生成訂位資料
    生成訂位資料();
  }, 3000);
}

function 生成訂位資料() {
  const 今天 = new Date();
  let 訂位數量 = 0;

  // 生成未來7天的訂位
  for (let 天數偏移 = 1; 天數偏移 <= 7; 天數偏移++) {
    const 日期 = new Date(今天);
    日期.setDate(日期.getDate() + 天數偏移);

    // 每天6-12個訂位
    const 當日訂位數 = 6 + Math.floor(Math.random() * 7);

    for (let i = 0; i < 當日訂位數; i++) {
      // 訂位時間主要在午餐和晚餐時段
      const 是否晚餐 = Math.random() > 0.4;
      const 小時 = 是否晚餐 ? 17 + Math.floor(Math.random() * 3) : 11 + Math.floor(Math.random() * 3);
      const 分鐘 = [0, 30][Math.floor(Math.random() * 2)];
      const 訂位時間 = new Date(日期);
      訂位時間.setHours(小時, 分鐘, 0, 0);

      const 會員編號 = Math.random() < 0.6 ? Math.floor(Math.random() * 15) + 1 : null;
      const 姓名列表 = ['王先生', '李小姐', '張先生', '陳小姐', '林先生', '黃小姐', '吳先生', '鄭小姐', '劉先生', '許小姐'];
      const 顧客姓名 = 姓名列表[Math.floor(Math.random() * 姓名列表.length)];
      const 顧客電話 = `09${Math.floor(Math.random() * 100000000).toString().padStart(8, '0')}`;
      const 桌位編號 = Math.floor(Math.random() * 25) + 1;
      const 人數 = 2 + Math.floor(Math.random() * 7);
      const 訂位狀態 = ['已確認', '待確認'][Math.floor(Math.random() * 2)];

      資料庫.run(
        `INSERT INTO 訂位 (會員編號, 顧客姓名, 顧客電話, 桌位編號, 人數, 訂位時間, 訂位狀態)
         VALUES (?, ?, ?, ?, ?, ?, ?)`,
        [會員編號, 顧客姓名, 顧客電話, 桌位編號, 人數, 訂位時間.toISOString(), 訂位狀態]
      );

      訂位數量++;
    }
  }

  setTimeout(() => {
    console.log(`✓ 已生成 ${訂位數量} 筆訂位`);
    console.log('\n' + '='.repeat(50));
    console.log('✅ 資料庫初始化完成！');
    console.log('='.repeat(50));
    console.log('\n您現在可以啟動伺服器：');
    console.log('  npm run server');
    console.log('\n或使用 npm script：');
    console.log('  npm run 後端\n');
    process.exit(0);
  }, 1500);
}
